const supportedLanguages = ["pt-BR", "en"];
const storageKey = "portfolio-language";
let currentLanguage = "pt-BR";

function translate(key, language = currentLanguage) {
    return translations[language]?.[key] ?? translations["pt-BR"]?.[key] ?? key;
}

function getSavedLanguage() {
    try {
        const savedLanguage = localStorage.getItem(storageKey);
        if (supportedLanguages.includes(savedLanguage)) return savedLanguage;
    } catch {
        // The site remains functional when browser storage is unavailable.
    }

    return navigator.language?.toLowerCase().startsWith("en") ? "en" : "pt-BR";
}

function applyLanguage(language) {
    currentLanguage = supportedLanguages.includes(language) ? language : "pt-BR";
    document.documentElement.lang = currentLanguage;

    document.querySelectorAll("[data-i18n]").forEach((element) => {
        element.textContent = translate(element.dataset.i18n);
    });

    const attributeMap = {
        "data-i18n-aria-label": "aria-label",
        "data-i18n-placeholder": "placeholder",
        "data-i18n-alt": "alt",
        "data-i18n-content": "content"
    };

    Object.entries(attributeMap).forEach(([dataAttribute, targetAttribute]) => {
        document.querySelectorAll(`[${dataAttribute}]`).forEach((element) => {
            element.setAttribute(targetAttribute, translate(element.getAttribute(dataAttribute)));
        });
    });

    const page = document.body.dataset.page;
    if (page) document.title = translate(`${page}.meta.title`);

    document.querySelectorAll(".lang-current").forEach((element) => {
        element.textContent = currentLanguage === "pt-BR" ? "PT-BR" : "EN";
    });

    document.querySelectorAll(".current-flag").forEach((flag) => {
        flag.classList.toggle("fi-br", currentLanguage === "pt-BR");
        flag.classList.toggle("fi-us", currentLanguage === "en");
    });

    document.querySelectorAll(".lang-option").forEach((option) => {
        option.setAttribute("aria-pressed", String(option.dataset.lang === currentLanguage));
    });

    const status = document.querySelector("[data-form-status][data-status-key]");
    if (status) status.textContent = translate(status.dataset.statusKey);

    try {
        localStorage.setItem(storageKey, currentLanguage);
    } catch {
        // Language still works for the current page without persistence.
    }
}

function initializeLanguageSwitcher() {
    const switcher = document.querySelector(".language-switcher");
    const toggle = switcher?.querySelector(".lang-toggle");
    const menu = switcher?.querySelector(".language-menu");
    if (!switcher || !toggle || !menu) return;

    const closeMenu = ({ restoreFocus = false } = {}) => {
        menu.hidden = true;
        toggle.setAttribute("aria-expanded", "false");
        if (restoreFocus) toggle.focus();
    };

    toggle.addEventListener("click", () => {
        const willOpen = menu.hidden;
        menu.hidden = !willOpen;
        toggle.setAttribute("aria-expanded", String(willOpen));
        if (willOpen) menu.querySelector(`[data-lang="${currentLanguage}"]`)?.focus();
    });

    menu.querySelectorAll(".lang-option").forEach((option) => {
        option.addEventListener("click", () => {
            applyLanguage(option.dataset.lang);
            closeMenu({ restoreFocus: true });
        });
    });

    document.addEventListener("click", (event) => {
        if (!switcher.contains(event.target)) closeMenu();
    });

    switcher.addEventListener("keydown", (event) => {
        if (event.key === "Escape") closeMenu({ restoreFocus: true });
    });
}

function initializeRevealAnimations() {
    const elements = document.querySelectorAll("[data-reveal]");

    if (!elements.length || !("IntersectionObserver" in window)) {
        elements.forEach((element) => element.classList.add("is-visible", "show"));
        return;
    }

    document.documentElement.classList.add("reveal-ready");
    const observer = new IntersectionObserver((entries) => {
        entries.forEach((entry) => {
            if (!entry.isIntersecting) return;
            entry.target.classList.add("is-visible", "show");
            observer.unobserve(entry.target);
        });
    }, { threshold: 0.16, rootMargin: "0px 0px -60px 0px" });

    elements.forEach((element) => observer.observe(element));
}

function initializeContactForm() {
    const form = document.querySelector("[data-contact-form]");
    const status = document.querySelector("[data-form-status]");
    if (!form || !status) return;

    form.addEventListener("submit", (event) => {
        event.preventDefault();
        if (!form.checkValidity()) {
            form.reportValidity();
            return;
        }

        status.dataset.statusKey = "contact.form.pending";
        status.textContent = translate("contact.form.pending");
        status.focus();
    });
}

applyLanguage(getSavedLanguage());
initializeLanguageSwitcher();
initializeRevealAnimations();
initializeContactForm();
